import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import request from 'supertest';
import jwt from 'jsonwebtoken';
import User from '../../src/models/User.js';
import { protect } from '../../src/middleware/auth.js';

const SECRET = 'refresh-access-contract-0123456789abcdef0123456789abcdef0123456789abcdef';
const USER_ID = '507f1f77bcf86cd799439011';

function protectedApp() {
    const app = express();
    app.get('/protected', protect, (req, res) => res.json({ id: String(req.user._id) }));
    return app;
}

function stubUserLookup() {
    const original = User.findById;
    const lookedUp = [];
    User.findById = id => {
        lookedUp.push(String(id));
        return { select: async () => ({ _id: id, role: 'citizen', status: 'active', tokenVersion: 0 }) };
    };
    return { lookedUp, restore: () => { User.findById = original; } };
}

test('access tokens generated by the refresh service authenticate protected HTTP routes', async () => {
    const previousSecret = process.env.JWT_SECRET;
    process.env.JWT_SECRET = SECRET;
    const lookup = stubUserLookup();

    try {
        const { generateAccessToken, verifyAccessToken } = await import('../../src/services/token.service.js');
        const token = generateAccessToken({ _id: USER_ID, email: 'user@example.com', role: 'citizen' });
        const decoded = verifyAccessToken(token);

        assert.equal(String(decoded.id), USER_ID);
        assert.equal(decoded.userId, undefined);
        await request(protectedApp())
            .get('/protected')
            .set('Authorization', `Bearer ${token}`)
            .expect(200, { id: USER_ID });
        assert.deepEqual(lookup.lookedUp, [USER_ID]);
    } finally {
        lookup.restore();
        if (previousSecret === undefined) delete process.env.JWT_SECRET;
        else process.env.JWT_SECRET = previousSecret;
    }
});

test('legacy refreshed access tokens remain usable but refresh tokens cannot access protected routes', async () => {
    const previousSecret = process.env.JWT_SECRET;
    process.env.JWT_SECRET = SECRET;
    const lookup = stubUserLookup();

    try {
        const legacyAccess = jwt.sign({ userId: USER_ID, type: 'access' }, SECRET, { expiresIn: '5m' });
        const refreshToken = jwt.sign({ userId: USER_ID, tokenId: 'token-id', type: 'refresh' }, SECRET, { expiresIn: '5m' });

        await request(protectedApp())
            .get('/protected')
            .set('Authorization', `Bearer ${legacyAccess}`)
            .expect(200, { id: USER_ID });
        await request(protectedApp())
            .get('/protected')
            .set('Authorization', `Bearer ${refreshToken}`)
            .expect(401);
        assert.deepEqual(lookup.lookedUp, [USER_ID]);
    } finally {
        lookup.restore();
        if (previousSecret === undefined) delete process.env.JWT_SECRET;
        else process.env.JWT_SECRET = previousSecret;
    }
});

test('POST /refresh-token returns an access token accepted by protected HTTP middleware', async () => {
    const previousSecret = process.env.JWT_SECRET;
    process.env.JWT_SECRET = SECRET;
    const originalFindById = User.findById;

    try {
        const { generateRefreshToken } = await import('../../src/services/token.service.js');
        const { default: authRouter } = await import('../../src/routes/auth.routes.js');
        const user = {
            _id: USER_ID,
            email: 'user@example.com',
            role: 'citizen',
            status: 'active',
            tokenVersion: 0,
            refreshTokens: [],
            save: async () => undefined
        };
        const issuedRefresh = generateRefreshToken(user);
        user.refreshTokens.push({ token: issuedRefresh.tokenId, expiresAt: new Date(Date.now() + 60_000) });
        User.findById = async () => user;

        const api = express();
        api.use(express.json());
        api.use('/api/v1/auth', authRouter);
        const refreshed = await request(api)
            .post('/api/v1/auth/refresh-token')
            .send({ refreshToken: issuedRefresh.token })
            .expect(200);

        assert.equal(typeof refreshed.body.accessToken, 'string');
        assert.equal(typeof refreshed.body.refreshToken, 'string');

        User.findById = id => ({ select: async () => ({ _id: id, role: 'citizen', status: 'active', tokenVersion: 0 }) });
        await request(protectedApp())
            .get('/protected')
            .set('Authorization', `Bearer ${refreshed.body.accessToken}`)
            .expect(200, { id: USER_ID });
    } finally {
        User.findById = originalFindById;
        if (previousSecret === undefined) delete process.env.JWT_SECRET;
        else process.env.JWT_SECRET = previousSecret;
    }
});
